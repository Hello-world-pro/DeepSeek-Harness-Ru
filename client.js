		/** Elements whose text must never be rewritten. */
		const SKIP = new Set(["SCRIPT", "STYLE", "TEXTAREA", "CODE", "PRE"]);
		/**
		* Replace known English package strings in text nodes under the given root.
		* @param root - subtree to scan.
		*/
		function translateRoot(root) {
			const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
				acceptNode(node) {
					const parent = node.parentElement;
					if (!parent || SKIP.has(parent.tagName)) return NodeFilter.FILTER_REJECT;
					return NodeFilter.FILTER_ACCEPT;
				}
			});
			let node;
			while ((node = walker.nextNode())) {
				const raw = node.nodeValue;
				if (!raw) continue;
				const trimmed = raw.trim();
				const translated = META_TRANSLATIONS[trimmed];
				if (!translated || translated === trimmed) continue;
				const start = raw.indexOf(trimmed);
				node.nodeValue = raw.slice(0, start) + translated;
			}
		}
		/**
		* Register the language, every namespace dictionary and the package-label
		* observer as owned effects, so unloading the bundle removes them again.
		* @param ctx - Client plugin context with the locale service injected.
		*/
		function apply(ctx) {
			ctx.effect(() => ctx.locale.addLanguage(LANGUAGE), "ru: language definition");
			for (const ns of Object.keys(DICTIONARIES)) {
				const entries = DICTIONARIES[ns];
				ctx.effect(() => ctx.locale.register(ns, "ru", entries), "ru: " + ns);
			}
			ctx.effect(() => {
				let scheduled = false;
				const run = () => {
					scheduled = false;
					try {
						translateRoot(document.body);
					} catch {
						/* the page may be mid-navigation */
					}
				};
				const observer = new MutationObserver(() => {
					if (scheduled) return;
					scheduled = true;
					setTimeout(run, 30);
				});
				observer.observe(document.body, { childList: true, subtree: true, characterData: true });
				run();
				return () => observer.disconnect();
			}, "ru: package label observer");
		}
		exports.apply = apply;
